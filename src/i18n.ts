export type Lang = 'zh' | 'en';
export type LangSetting = 'auto' | Lang;

const DICTS: Record<Lang, Record<I18nKey, string>> = { zh, en };
let current: Lang = 'zh';

export function setLanguage(lang: Lang): void { current = lang; }
export function getCurrentLanguage(): Lang { return current; }

/* Obsidian 的语言代码（zh、zh-TW、en、de…）→ 本插件支持的语言：中文系用中文，其余用英文 */
export function resolveLanguage(setting: LangSetting, obsidianLang: string | null | undefined): Lang {
  if (setting === 'zh' || setting === 'en') return setting;
  return /^zh/i.test(obsidianLang || '') ? 'zh' : 'en';
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key];
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
